#!/bin/sh
# Golden tests for Dolphin. Usage: run_tests.sh path/to/dolphin
#
# Every program runs at each thread count in $THREADS (default "1 2 4 8 auto";
# "auto" passes no --threads, so the pool sizes itself and adapts to load).
# Parallel runs must produce byte-identical output to sequential ones; that's
# the core promise of the M2 runtime.
#   cases/X.dol + X.out    stdout must match, exit 0
#   cases/X.dol + X.err    stderr must match, exit nonzero
#   cases/X.dol + X.needs  `dolphin --needs` output must match
#   cases/X.dol + X.both   stdout and stderr together (2>&1) must match, exit nonzero:
#                          checks that output printed before an error appears before it
#   cases/X.requires       optional features (words from `dolphin --features`, e.g. zstd,
#                          archive) the case needs; without them it's skipped, and counted
# Plus the examples in ../examples against the bulletins and fixtures in data/.
set -u
BIN=$(cd "$(dirname "$1")" && pwd)/$(basename "$1")
THREADS=${THREADS:-"1 2 4 8 auto"}
# Every test runs on each engine unless ENGINE picks one: tree, pcode,
# pcode0 (p-code without optimizations, so each optimization is checked
# against the plain form), or dcl (compile with -c, then run the .dcl file:
# the loader and verifier must give back exactly the same program).
if [ -z "${ENGINE:-}" ]; then
    rc=0
    for e in tree pcode pcode0 dcl; do
        echo "== engine: $e"
        ENGINE=$e "$0" "$@" || rc=1
    done
    exit $rc
fi
# Thread-count (and engine) arguments for one entry of $THREADS.
thr() {
    case "$ENGINE" in
    pcode0) echo "--engine pcode --opt 0" ;;
    dcl) ;;   # a .dcl is always p-code
    *) echo "--engine $ENGINE" ;;
    esac
    [ "$1" = auto ] || echo "--threads $1"
}
# runp PROGRAM [dolphin options...] [-- program args...]
# Runs PROGRAM; with ENGINE=dcl, compiles it once and runs the .dcl instead.
# Compile-time output (warnings, syntax errors) is replayed on stderr, so
# expected-output files compare the same way for every engine.
DCLDIR=$(mktemp -d)
trap 'rm -rf "$DCLDIR"' EXIT
runp() {
    p=$1; shift
    opts=""
    while [ $# -gt 0 ] && [ "$1" != -- ]; do opts="$opts $1"; shift; done
    [ "${1:-}" = -- ] && shift
    if [ "$ENGINE" != dcl ]; then "$BIN" $opts "$p" "$@"; return; fi
    d="$DCLDIR/$(echo "$p" | tr '/.' '__').dcl"
    if [ ! -f "$d.rc" ]; then "$BIN" -c -o "$d" "$p" 2>"$d.cerr"; echo $? >"$d.rc"; fi
    cat "$d.cerr" >&2
    [ "$(cat "$d.rc")" = 0 ] || return 1
    "$BIN" $opts "$d" "$@"
}
cd "$(dirname "$0")/cases" || exit 2
pass=0 fail=0 skipped=0
FEATURES=" $("$BIN" --features | tr '\n' ' ') "
report() { if [ "$1" = 0 ]; then pass=$((pass+1)); else fail=$((fail+1)); echo "FAIL: $2"; fi; }
for src in *.dol; do
    name=${src%.dol}
    if [ -f "$name.requires" ]; then
        missing=""
        for feat in $(cat "$name.requires"); do
            case "$FEATURES" in *" $feat "*) ;; *) missing="$missing $feat" ;; esac
        done
        if [ -n "$missing" ]; then
            echo "skip: $name (not compiled in:$missing)"
            skipped=$((skipped+1))
            continue
        fi
    fi
    for t in $THREADS; do
        if [ -f "$name.out" ]; then
            runp "$src" $(thr "$t") 2>/dev/null | diff -u "$name.out" - >/dev/null; report $? "$name (stdout, $t threads)"
        fi
        if [ -f "$name.out" ] && [ "$t" = 1 ]; then   # the synchronous-output path too
            "$BIN" --threads 1 --sync-output "$src" 2>/dev/null | diff -u "$name.out" - >/dev/null; report $? "$name (stdout, --sync-output)"
        fi
        if [ -f "$name.both" ]; then
            runp "$src" $(thr "$t") > /tmp/dolphin_both.$$ 2>&1
            diff -u "$name.both" /tmp/dolphin_both.$$ >/dev/null; report $? "$name (stdout+stderr order, $t threads)"
            rm -f /tmp/dolphin_both.$$
        fi
        if [ -f "$name.err" ]; then
            if runp "$src" $(thr "$t") >/dev/null 2>/tmp/dolphin_err.$$; then report 1 "$name (expected failure, $t threads)"
            else diff -u "$name.err" /tmp/dolphin_err.$$ >/dev/null; report $? "$name (stderr, $t threads)"; fi
        fi
    done
    if [ -f "$name.needs" ]; then
        "$BIN" --needs "$src" 2>/dev/null | diff -u "$name.needs" - >/dev/null; report $? "$name (needs)"
    fi
done
rm -f /tmp/dolphin_err.$$
cd ..
example() {   # example <name> <expected-output> <args...>
    name=$1 expected=$2; shift 2
    for t in $THREADS; do
        runp "../examples/$name.dol" $(thr "$t") -- "$@" 2>&1 | diff -u "$expected" - >/dev/null; report $? "example $name $* ($t threads)"
    done
}
example grib_ls grib_ls.out data/synthetic.grib2
# Expected METAR output is generated by CPython (py_oracle.py), not by dolphin.
example metar metar_bulletin.out data/metar_bulletin.txt
example metar metar_edge.out data/metar_edge.txt
"$BIN" --needs ../examples/metar.dol 2>&1 | diff -u metar.needs - >/dev/null; report $? "metar needs"
# Decision 17 demo: with one thread, "first to return" is program order, so the
# output is fixed. (In parallel it varies by design; see the example's comments.)
"$BIN" --threads 1 ../examples/first_failure.dol 2>&1 | diff -u first_failure_seq.out - >/dev/null; report $? "first_failure (sequential)"

# Backpressure: 250,000 lines (~17 MB) through the 8 MB output queue, into a
# slow-ish pipe. Every line must arrive, in order.
"$BIN" --stats flood.dol 2>/tmp/dolphin_flood_stats.$$ | (sleep 1; awk 'NR<=250000 && $1 != sprintf("%07d", NR-1) {bad=1} END {exit !(NR==250001 && !bad && $0=="done")}')
report $? "output backpressure (all lines, in order)"
rm -f /tmp/dolphin_flood_stats.$$
# The published HTML reference is generated from doc/REFERENCE.md and must match it.
if command -v python3 >/dev/null 2>&1; then
    python3 ../../../doc/build_reference_html.py --check; report $? "doc/reference.html matches doc/REFERENCE.md"
fi
echo "$pass passed, $fail failed, $skipped skipped"
[ "$fail" = 0 ]
